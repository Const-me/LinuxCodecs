using System.Buffers;
namespace MakeCMake;

static class Generator
{
	public static void generate( string path )
	{
		Sources sources = Sources.parseProject( path );
		string folder = Path.GetDirectoryName( path )!;
		string projectName = Path.GetFileName( path );

		string varName = Path.GetFileNameWithoutExtension( path ).ToUpperInvariant();
		string dest = Path.ChangeExtension( path, ".cmake" );
		writeSources( dest, varName + "_SOURCES", folder, projectName, sources.cpp );

		if( sources.nasm.Count <= 0 )
			return;

		dest = Path.ChangeExtension( dest, null );
		dest += ".nasm.cmake";
		writeSources( dest, varName + "_NASM", folder, projectName, sources.nasm );
	}

	static void writeSources( string destPath, string varName, string folder, string projectName, List<string> list )
	{
		using var w = File.CreateText( destPath );
		w.NewLine = "\n";

		w.WriteLine( "# Generated by MakeCMake from {0}", projectName );
		w.WriteLine( "set( {0}", varName );
		foreach( string abs in list )
		{
			string rel = Path.GetRelativePath( folder, abs ).forwardSlashes();
			if( rel.ContainsAny( forbiddenChars ) )
				throw new ArgumentException( "Malformed source file: " + rel );
			w.WriteLine( "\t${{CMAKE_CURRENT_SOURCE_DIR}}/{0}", rel );
		}
		w.Write( ")" );
	}

	static readonly SearchValues<char> forbiddenChars = SearchValues.Create( "\r\n \t:\"\'?*;$#," );

	/// <summary>Replace back slashes with forward ones, for Linux compatibility</summary>
	public static string forwardSlashes( this string path ) => path.Replace( '\\', '/' );
}